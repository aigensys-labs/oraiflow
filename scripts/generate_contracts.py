#!/usr/bin/env python3
"""Generate frontend contract metadata from the canonical JSON registry."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "shared/contracts/registry.json"
TARGET = ROOT / "apps/web/src/generated/contracts.js"


def render() -> str:
    """Render the frontend contract artifact from the canonical registry."""
    raw = SOURCE.read_bytes()
    registry = json.loads(raw)
    digest = hashlib.sha256(raw).hexdigest()
    serialized = json.dumps(registry, ensure_ascii=False, separators=(",", ":"))
    return (
        "// Generated by scripts/generate_contracts.py; do not edit manually.\n"
        f"export const CONTRACT_REGISTRY_SHA256 = {json.dumps(digest)};\n"
        f"export const CONTRACT_REGISTRY = {serialized};\n"
    )


def main() -> int:
    """Generate or validate derived frontend contract artifacts."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != generated:
            print(
                "Frontend capability contracts are stale. Run: python scripts/generate_contracts.py"
            )
            return 1
        print("Frontend capability contracts are up to date.")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(generated, encoding="utf-8")
    print(f"Generated {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
